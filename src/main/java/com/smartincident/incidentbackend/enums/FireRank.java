package com.smartincident.incidentbackend.enums;

/**
 * Rank structure of the Tanzania Fire and Rescue Force (TFRF).
 * Listed from highest to lowest.
 */
public enum FireRank {
    CFO,          // Chief Fire Officer
    DCFO,         // Deputy Chief Fire Officer
    SDO,          // Senior Divisional Officer
    DO,           // Divisional Officer
    ADO,          // Assistant Divisional Officer
    SO,           // Station Officer
    ASO,          // Assistant Station Officer
    SUB_OFFICER,  // Sub-Officer
    LEADING_FM,   // Leading Fireman
    FIREMAN       // Fireman (entry rank)
}
